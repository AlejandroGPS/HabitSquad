import { beforeEach, describe, expect, it, vi } from 'vitest'
import { createMockSquadSettings } from '../mocks/configuracionEscuadron.js'
import { configuracionEscuadronScreen } from './configuracionEscuadron.js'

let api
let page
const findButton = (label) => [...page.querySelectorAll('button')].find((node) => node.textContent === label || node.getAttribute('aria-label') === label)
const click = (label) => findButton(label).click()
const tab = (label) => page.querySelectorAll('[role="tab"]')[['General', 'Miembros', 'Invitaciones'].indexOf(label)].click()
const changeName = (value) => {
  const input = page.querySelector('[name="nombre"]')
  input.value = value
  input.dispatchEvent(new Event('input', { bubbles: true }))
}
const submit = () => page.querySelector('form').dispatchEvent(new Event('submit', { cancelable: true }))
async function mount(value = api) {
  page = configuracionEscuadronScreen({ api: value, id: 'demo', demo: true })
  document.body.replaceChildren(page)
  await vi.waitFor(() => expect(page.querySelector('[aria-busy]').getAttribute('aria-busy')).toBe('false'))
}

describe('pantalla de configuración', () => {
  beforeEach(async () => {
    api = createMockSquadSettings()
    await mount()
  })
  it('mantiene el menú del panel con Configuración activa y las rutas del escuadrón de origen', async () => {
    page = configuracionEscuadronScreen({ api, id: 'demo', demo: true, panelHref: '/escuadrones/panel?id=7' })
    document.body.replaceChildren(page)
    await vi.waitFor(() => expect(page.querySelector('input')).not.toBeNull())
    const nav = page.querySelector('aside nav')
    expect([...nav.children].map((node) => node.textContent)).toEqual(['Escuadrón', 'Racha', 'Alertas', 'Mi hábito', 'Configuración'])
    expect(nav.querySelector('[aria-current="page"]').getAttribute('href')).toBe('/escuadrones/configuracion?origen=7')
    expect(nav.querySelector('a[href="/escuadrones/panel?id=7"]').hasAttribute('data-link')).toBe(true)
    expect(nav.querySelector('a[href="/habito?escuadron=7"]')).not.toBeNull()
    expect(page.querySelector('header a[aria-label="Volver al panel"]').getAttribute('href')).toBe('/escuadrones/panel?id=7')
  })
  it('guarda los tres campos juntos y mantiene el resumen guardado mientras se edita', async () => {
    changeName('  Nuevo equipo  ')
    click('Público')
    click('Aumentar plazas')
    expect(page.querySelector('.settings-summary').textContent).toContain('Privado · 3 de 5')
    expect(page.textContent).toContain('Tienes cambios sin guardar')
    submit()
    await vi.waitFor(() => expect(page.textContent).toContain('Cambios guardados.'))
    expect(page.querySelector('.settings-summary').textContent).toContain('Nuevo equipoPúblico · 3 de 6')
    expect(page.querySelector('input').value).toBe('Nuevo equipo')
    expect(findButton('Guardar cambios').disabled).toBe(true)
    expect(await api.get('demo')).toMatchObject({ nombre: 'Nuevo equipo', publico: true, capacidad: 6 })
  })
  it('descarta todos los cambios, conserva el borrador al cambiar de pestaña y valida el nombre', () => {
    changeName('Borrador')
    click('Público')
    click('Aumentar plazas')
    tab('Miembros')
    tab('General')
    expect(page.querySelector('input').value).toBe('Borrador')
    click('Descartar')
    expect(page.querySelector('input').value).toBe('Los Inquebrantables')
    expect(findButton('Privado').getAttribute('aria-pressed')).toBe('true')
    expect(page.querySelector('output').value).toBe('5')
    changeName('   ')
    submit()
    expect(page.querySelector('input').getAttribute('aria-invalid')).toBe('true')
    expect(findButton('Guardar cambios').disabled).toBe(false)
  })
  it('limita las plazas a los miembros actuales y a diez', () => {
    expect(findButton('Reducir plazas').className).toContain('cursor-pointer')
    expect(findButton('Aumentar plazas').className).toContain('cursor-pointer')
    for (let i = 0; i < 10; i++) click('Reducir plazas')
    expect(page.querySelector('output').value).toBe('3')
    expect(findButton('Reducir plazas').disabled).toBe(true)
    for (let i = 0; i < 12; i++) click('Aumentar plazas')
    expect(page.querySelector('output').value).toBe('10')
    expect(findButton('Aumentar plazas').disabled).toBe(true)
  })
  it('navega las pestañas con teclado y conserva atributos accesibles', () => {
    const tabs = [...page.querySelectorAll('[role="tab"]')]
    tabs[0].dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }))
    expect(tabs[1].getAttribute('aria-selected')).toBe('true')
    expect(document.activeElement).toBe(tabs[1])
    expect(page.querySelector('[role="tabpanel"]').getAttribute('aria-labelledby')).toBe(tabs[1].id)
    tabs[1].dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true }))
    expect(tabs[2].tabIndex).toBe(0)
    expect(tabs[0].tabIndex).toBe(-1)
  })
  it('exige confirmar la expulsión, permite cancelarla y actualiza las plazas libres', async () => {
    tab('Miembros')
    expect(findButton('Expulsar a alegarcia')).toBeUndefined()
    click('Expulsar a laura.run')
    expect((await api.get('demo')).miembros).toHaveLength(3)
    click('Cancelar')
    expect(findButton('Confirmar expulsión de laura.run')).toBeUndefined()
    click('Expulsar a laura.run')
    click('Confirmar expulsión de laura.run')
    await vi.waitFor(() => expect(page.textContent).toContain('laura.run ha salido'))
    expect(page.querySelectorAll('.settings-free-avatar')).toHaveLength(3)
    expect((await api.get('demo')).miembros).toHaveLength(2)
  })
  it('mantiene los cambios pendientes de General después de expulsar', async () => {
    changeName('Borrador')
    tab('Miembros')
    click('Expulsar a sergiofb')
    click('Confirmar expulsión de sergiofb')
    await vi.waitFor(() => expect(page.textContent).toContain('sergiofb ha salido'))
    tab('General')
    expect(page.querySelector('input').value).toBe('Borrador')
    expect(page.textContent).toContain('Tienes cambios sin guardar')
    expect(page.querySelector('.settings-summary').textContent).toContain('2 de 5')
  })
  it('copia el código vigente y permite renovarlo con confirmación', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
    tab('Invitaciones')
    click('Copiar código')
    await vi.waitFor(() => expect(page.textContent).toContain('Código copiado.'))
    expect(writeText).toHaveBeenCalledWith('K7P2QX')
    click('Generar otro código')
    expect((await api.get('demo')).codigo).toBe('K7P2QX')
    click('Confirmar nuevo código')
    await vi.waitFor(() => expect(page.textContent).toContain('Nuevo código generado.'))
    expect(page.querySelector('code').textContent).not.toBe('K7P2QX')
    expect(page.querySelector('code').textContent).toBe((await api.get('demo')).codigo)
  })
  it('indica cómo copiar manualmente si no hay portapapeles', async () => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined })
    tab('Invitaciones')
    click('Copiar código')
    await vi.waitFor(() => expect(page.textContent).toContain('cópialo manualmente'))
  })
  it('exige una segunda pulsación para eliminar y retira los controles', async () => {
    tab('Miembros')
    click('Eliminar')
    expect(page.textContent).toContain('No se puede deshacer')
    await expect(api.get('demo')).resolves.toBeDefined()
    click('Confirmar eliminación')
    await vi.waitFor(() => expect(page.textContent).toContain('Escuadrón de ejemplo eliminado'))
    expect(page.querySelector('[role="tablist"]').hidden).toBe(true)
    await expect(api.get('demo')).rejects.toThrow()
  })
  it('muestra solo un aviso y el retorno para quien no administra', async () => {
    await mount(createMockSquadSettings({ esAdministrador: false }))
    expect(page.textContent).toContain('Solo para el administrador')
    expect(page.querySelector('[role="tablist"]').hidden).toBe(true)
    expect(page.querySelector('input')).toBeNull()
    expect(findButton('Guardar cambios')).toBeUndefined()
    expect(page.querySelector('.settings-panel a').getAttribute('href')).toBe('/escuadrones')
  })
  it('muestra errores de carga y permite reintentar', async () => {
    const get = vi.fn().mockRejectedValueOnce(new Error('Fallo de conexión')).mockImplementation(() => api.get('demo'))
    await mount({ ...api, get })
    expect(page.querySelector('[role="alert"]').textContent).toBe('Fallo de conexión')
    click('Reintentar')
    await vi.waitFor(() => expect(page.querySelector('input')).not.toBeNull())
    expect(get).toHaveBeenCalledTimes(2)
  })
  it('bloquea envíos repetidos y conserva el borrador ante un error de guardado', async () => {
    let rejectUpdate
    const update = vi.fn(() => new Promise((resolve, reject) => { rejectUpdate = reject }))
    await mount({ ...api, update })
    changeName('Mi equipo')
    submit()
    submit()
    expect(update).toHaveBeenCalledTimes(1)
    expect([...page.querySelectorAll('.settings-content button, .settings-content input')].every((node) => node.disabled)).toBe(true)
    rejectUpdate(new Error('No se pudo guardar'))
    await vi.waitFor(() => expect(page.querySelector('[role="alert"]').textContent).toBe('No se pudo guardar'))
    expect(page.querySelector('input').value).toBe('Mi equipo')
    expect(findButton('Guardar cambios').disabled).toBe(false)
    expect(page.querySelector('.settings-summary').textContent).toContain('Los Inquebrantables')
  })
  it('no realiza peticiones de red para cargar, guardar, expulsar ni regenerar', async () => {
    const fetch = vi.spyOn(globalThis, 'fetch')
    changeName('Equipo offline')
    submit()
    await vi.waitFor(() => expect(page.textContent).toContain('Cambios guardados'))
    tab('Miembros')
    click('Expulsar a laura.run')
    click('Confirmar expulsión de laura.run')
    await vi.waitFor(() => expect(page.textContent).toContain('laura.run ha salido'))
    tab('Invitaciones')
    click('Generar otro código')
    click('Confirmar nuevo código')
    await vi.waitFor(() => expect(page.textContent).toContain('Nuevo código generado'))
    expect(fetch).not.toHaveBeenCalled()
    fetch.mockRestore()
  })
})
